const styles = JSON.parse(await fs.readFile(FILE, 'utf8'));
const missing = [];
for (const s of styles) {
  if (!TAGS[s.id]) {
    missing.push(s.id);
    continue;
  }
  s.tags = TAGS[s.id];
}
if (missing.length) {
  console.error('以下条目没有标签方案，请补充：', missing.join(', '));
  process.exit(1);
}

await fs.writeFile(FILE, JSON.stringify(styles, null, 2), 'utf8');

const count = new Map();
for (const s of styles) for (const t of s.tags) count.set(t, (count.get(t) || 0) + 1);
const shared = [...count.entries()].filter(([, n]) => n > 1).sort((a, b) => b[1] - a[1]);
