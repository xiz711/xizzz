const MEDIA_COMMENT = [
  '/* 媒体层承担视差位移与缩放，指针位移交给外层，二者互不干扰。',
  '   放大比例按 inset 的余量反算：只要内层缩放 ≥ 1.07，任何位移都不会露出边缘。',
  '   注意：这里不加 transition —— 视差由 rAF 每帧写入，交给 CSS 过渡会互相打架。 */',
];

let changed = 0;
for (const [num, text] of Object.entries(FIX)) {
  const i = Number(num) - 1;
  if (lines[i] === undefined) continue;
  if (text === null) {
    lines[i] = MEDIA_COMMENT.join('\n');
  } else {
    lines[i] = text;
  }
  changed++;
}

// 兜底：声明块与 content 属性里残留的乱码中点
const out = lines.join('\n').replace(/content: '[^']*'; margin-left: 0\.32rem; color: var\(--line\);/, "content: '·'; margin-left: 0.32rem; color: var(--line);");

fs.writeFileSync(FILE, out, 'utf8');

const still = out.split('\n').filter((l) => /[\u4e00-\u9fff]/.test(l) && /[鎺甯浠绐棣銆濯鏀鎸璇鍒鏍璇浠瀵缂鍙婃]/.test(l));
const open = (out.match(/\/\*/g) || []).length;
const close = (out.match(/\*\//g) || []).length;
console.log(`修复 ${changed} 行；注释配对 opens=${open} closes=${close}`);
